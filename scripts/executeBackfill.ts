async function run() {
  console.log('=== Step 1: Pre-check localStorage and Reload SnapshotService Memory ===');
  SnapshotService.reloadFromLocalStorage();
  const stored = JSON.parse(global.localStorage.getItem('cfo_monthly_snapshots_v1'));
  console.log('2026-04 assets count:', stored.assetSnapshots['2026-04'].length);
  console.log('2026-04 debts count:', stored.debtSnapshots['2026-04'].length);
  console.log('2026-05 assets count:', stored.assetSnapshots['2026-05'].length);
  console.log('2026-05 debts count:', stored.debtSnapshots['2026-05'].length);

  console.log('\n=== Step 2: Running backfillConfirmedSnapshotsToFirestore ===');
  const results = await backfillConfirmedSnapshotsToFirestore(['2026-04', '2026-05']);
  console.log('Backfill results:', JSON.stringify(results, null, 2));

  console.log('\n=== Step 3: READ BACK Verification from Firestore ===');
  for (const monthKey of ['2026-04', '2026-05']) {
    const docRef = doc(db, 'households', 'family_cfo', 'snapshots', monthKey);
    const snap = await getDoc(docRef);
    if (!snap.exists()) {
      console.error(`❌ snapshots/${monthKey} DOES NOT EXIST in Firestore!`);
    } else {
      const data = snap.data();
      const mSnap = data.monthlySnapshot || {};
      const aSnaps = data.assetSnapshots || [];
      const dSnaps = data.debtSnapshots || [];
      const sumAssets = aSnaps.reduce((sum: number, a: any) => sum + (a.value || a.assetValueSnapshot || 0), 0);
      const sumDebts = dSnaps.reduce((sum: number, d: any) => sum + (d.openingPrincipal || d.debtBalanceSnapshot || 0), 0);

      console.log(`\n--- Firestore READ BACK [${monthKey}] ---`);
      console.log(`- Exists: YES`);
      console.log(`- Status: ${mSnap.status}`);
      console.log(`- Asset Count: ${aSnaps.length}건 (Expected: 4건)`);
      console.log(`- Asset Total: ${sumAssets.toLocaleString()}원 (Expected: 4,150,000,000원)`);
      console.log(`- Debt Count: ${dSnaps.length}건 (Expected: 13건)`);
      console.log(`- Debt Total: ${sumDebts.toLocaleString()}원 (Expected: 2,510,020,000원)`);
    }
  }

  process.exit(0);
}

run().catch((err) => {
  console.error('Fatal error during backfill:', err);
  process.exit(1);
});
